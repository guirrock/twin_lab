import pandas as pd
import numpy as np
import scipy.stats as stats
import statsmodels.api as sm
from statsmodels.formula.api import ols
import matplotlib.pyplot as plt
import seaborn as sns
from math import pi
import warnings
warnings.filterwarnings("ignore")

# =========================================================
# 1. CARREGAR E LIMPAR DADOS
# =========================================================
file_path = "Ficha de Observação - IDSA (Medidas e Erros).xlsx"
sheets = [
    'Observação Caroline - Turma exp',
    'Observação Guilherme- Turma exp',
    'Observação Guilherme- Turma con',
    'Observação Lierson- Turma contr'
]

all_data = []
for s in sheets:
    df = pd.read_excel(file_path, sheet_name=s, header=3)
    df = df.dropna(subset=['Total (Máx 18)'])
    df = df[df['Nome do Aluno'].notna() & (~df['Nome do Aluno'].str.contains('Média', na=False, case=False))].copy()

    df['Turma'] = 'Grupo Experimental' if 'exp' in s.lower() else 'Grupo Controle'
    df['Avaliador'] = s.split('-')[0].replace('Observação ', '').strip()

    cols = [c for c in df.columns if ' (0-2)' in c] + ['Total (Máx 18)']
    for c in cols:
        df[c] = pd.to_numeric(df[c], errors='coerce')

    all_data.append(df)

df_full = pd.concat(all_data, ignore_index=True)
crit_cols = [c for c in df_full.columns if ' (0-2)' in c]

# O df_g filtra as notas do Guilherme para as comparações entre turmas e gráficos
df_g = df_full[df_full['Avaliador'] == 'Guilherme']

sns.set_context("paper", font_scale=1.4)
sns.set_style("ticks")


# =========================================================
# 2. GERAÇÃO DE GRÁFICOS
# =========================================================
print("Gerando Gráficos...")

# Boxplot
plt.figure(figsize=(7, 6))
ax = sns.boxplot(x='Turma', y='Total (Máx 18)', data=df_g, palette=["#4C72B0", "#C44E52"], width=0.5, linewidth=2)
sns.stripplot(x='Turma', y='Total (Máx 18)', data=df_g, color=".25", alpha=0.6, jitter=0.1, size=6)
plt.title('Distribuição do Escore Global de Segurança (IDSA)', pad=15, fontweight='bold')
plt.ylabel('Escore Total (Máx 18 pontos)', fontweight='bold')
plt.xlabel('')
plt.ylim(0, 19)
sns.despine()
plt.tight_layout()
plt.savefig('Figura_1_Boxplot_Artigo.png', dpi=300)
plt.close()

# Radar
medias = df_g.groupby('Turma')[crit_cols].mean()
categorias = [c.split('.')[1].replace(' (0-2)', '').strip() for c in crit_cols]
N = len(categorias)
angulos = [n / float(N) * 2 * pi for n in range(N)]
angulos += angulos[:1]

fig, ax = plt.subplots(figsize=(8, 8), subplot_kw=dict(polar=True))
ax.set_theta_offset(pi / 2)
ax.set_theta_direction(-1)
plt.xticks(angulos[:-1], categorias, size=11, fontweight='bold')
ax.set_rlabel_position(30)
plt.yticks([0.5, 1.0, 1.5, 2.0], ["0,5", "1,0", "1,5", "2,0"], color="grey", size=10)
plt.ylim(0, 2.1)

cores = {'Grupo Experimental': '#4C72B0', 'Grupo Controle': '#C44E52'}
for index, row in medias.iterrows():
    valores = row.values.flatten().tolist()
    valores += valores[:1]
    ax.plot(angulos, valores, linewidth=2.5, linestyle='solid', label=index, color=cores[index])
    ax.fill(angulos, valores, alpha=0.15, color=cores[index])

plt.legend(loc='upper right', bbox_to_anchor=(1.3, 1.1), frameon=True)
plt.title('Média de Desempenho por Rubrica de Segurança', size=14, fontweight='bold', y=1.08)
plt.tight_layout()
plt.savefig('Figura_2_Radar_Artigo.png', dpi=300)
plt.close()
print("-> Figuras exportadas com sucesso em 300 DPI.\n")


# =========================================================
# 3. ANÁLISE ESTATÍSTICA E EXPORTAÇÃO PARA EXCEL
# =========================================================
print("Calculando Estatísticas e gerando Excel...")

exp_scores = df_g[df_g['Turma'] == 'Grupo Experimental']['Total (Máx 18)']
con_scores = df_g[df_g['Turma'] == 'Grupo Controle']['Total (Máx 18)']
n1, n2 = len(exp_scores), len(con_scores)

# --- 3.1. Teste de Normalidade (Shapiro-Wilk) ---
stat_exp, p_shapiro_exp = stats.shapiro(exp_scores)
stat_con, p_shapiro_con = stats.shapiro(con_scores)

df_shapiro = pd.DataFrame({
    'Grupo': ['Experimental (n=9)', 'Controle (n=13)'],
    'Estatística W': [stat_exp, stat_con],
    'Valor-p': [p_shapiro_exp, p_shapiro_con],
    'Pressuposto de Normalidade': ['Violado (Não Normal)' if p_shapiro_exp < 0.05 else 'Atendido (Normal)',
                                   'Violado (Não Normal)' if p_shapiro_con < 0.05 else 'Atendido (Normal)']
})

# --- 3.2. Estatística Descritiva e Teste de Hipótese (Global) ---
mean_exp, std_exp = exp_scores.mean(), exp_scores.std(ddof=1)
mean_con, std_con = con_scores.mean(), con_scores.std(ddof=1)
u_stat_global, p_val_global = stats.mannwhitneyu(exp_scores, con_scores, alternative='two-sided')

pooled_std = np.sqrt(((n1 - 1) * std_exp**2 + (n2 - 1) * std_con**2) / (n1 + n2 - 2))
cohens_d = (mean_exp - mean_con) / pooled_std
r_biserial_global = 1 - (2 * u_stat_global) / (n1 * n2)

df_global = pd.DataFrame({
    'Métrica': ['Média', 'Desvio Padrão', 'Mediana', 'Estatística U', 'Valor-p', "Cohen's d", 'Rank-Biserial r'],
    'Grupo Experimental (n=9)': [mean_exp, std_exp, exp_scores.median(), u_stat_global, p_val_global, cohens_d, r_biserial_global],
    'Grupo Controle (n=13)': [mean_con, std_con, con_scores.median(), u_stat_global, p_val_global, cohens_d, r_biserial_global]
})

# --- 3.3. Comparação Múltipla de Critérios (Correção de Holm) ---
criterios_stats = []
p_values = {}

for col in crit_cols:
    data_exp_crit = df_g[df_g['Turma'] == 'Grupo Experimental'][col]
    data_con_crit = df_g[df_g['Turma'] == 'Grupo Controle'][col]

    # Extração de Médias, Medianas e DPs
    med_exp, mean_exp, std_exp = data_exp_crit.median(), data_exp_crit.mean(), data_exp_crit.std(ddof=1)
    med_con, mean_con, std_con = data_con_crit.median(), data_con_crit.mean(), data_con_crit.std(ddof=1)

    # Prevenção de NaN no Desvio Padrão caso os valores sejam idênticos
    std_exp = 0.0 if pd.isna(std_exp) else std_exp
    std_con = 0.0 if pd.isna(std_con) else std_con

    if len(data_exp_crit.unique()) == 1 and len(data_con_crit.unique()) == 1 and data_exp_crit.iloc[0] == data_con_crit.iloc[0]:
        u_stat_crit = (n1 * n2) / 2.0 # Empate perfeito
        p_crit = 1.0
    else:
        u_stat_crit, p_crit = stats.mannwhitneyu(data_exp_crit, data_con_crit, alternative='two-sided')

    r_biserial_crit = 1 - (2 * u_stat_crit) / (n1 * n2)
    p_values[col] = p_crit

    criterios_stats.append({
        'Critério': col,
        'GE (n=9) - Mediana (Média ± DP)': f"{med_exp:.1f} ({mean_exp:.2f} ± {std_exp:.2f})",
        'GC (n=13) - Mediana (Média ± DP)': f"{med_con:.1f} ({mean_con:.2f} ± {std_con:.2f})",
        'Estatística U': u_stat_crit,
        'Rank-Biserial (r)': r_biserial_crit,
        'Valor-p Bruto': p_crit # Mantendo o Valor-p Bruto
    })

# Aplicar Correção de Holm
sorted_p = sorted(p_values.items(), key=lambda x: x[1])
holm_p, m = {}, len(sorted_p)
for i, (col, p) in enumerate(sorted_p):
    adjusted_p = min(max(p * (m - i), holm_p.get(sorted_p[i-1][0], 0) if i > 0 else 0), 1.0)
    holm_p[col] = adjusted_p

# Montar Tabela Completa dos Critérios
df_criterios = pd.DataFrame(criterios_stats)
df_criterios['Valor-p (Holm)'] = df_criterios['Critério'].map(holm_p)
df_criterios['Significativo (p<0.05)'] = df_criterios['Valor-p (Holm)'].apply(lambda x: 'Sim' if x < 0.05 else 'Não')

# --- Adicionar a LINHA 10 (Escore Total em Porcentagem) ---
exp_pct = exp_scores / 18 * 100
con_pct = con_scores / 18 * 100

linha_total = pd.DataFrame([{
    'Critério': 'Escore Total IDSA (%)',
    'GE (n=9) - Mediana (Média ± DP)': f"{exp_pct.median():.1f}% ({exp_pct.mean():.1f}% ± {exp_pct.std(ddof=1):.1f}%)",
    'GC (n=13) - Mediana (Média ± DP)': f"{con_pct.median():.1f}% ({con_pct.mean():.1f}% ± {con_pct.std(ddof=1):.1f}%)",
    'Estatística U': u_stat_global,
    'Rank-Biserial (r)': r_biserial_global,
    'Valor-p Bruto': p_val_global,
    'Valor-p (Holm)': p_val_global, # Repete pois não há penalização no escore global
    'Significativo (p<0.05)': 'Marginal (Não)'
}])

df_criterios = pd.concat([df_criterios, linha_total], ignore_index=True)

# --- 3.4. Confiabilidade Interavaliadores (ICC) ---
def calculate_icc(df):
    means = df.groupby('Avaliador')[crit_cols].mean().reset_index()
    long_df = means.melt(id_vars='Avaliador', value_vars=crit_cols, var_name='Target', value_name='Score')
    model = ols('Score ~ C(Target) + C(Avaliador)', data=long_df).fit()
    anova = sm.stats.anova_lm(model, typ=2)
    MS_r = anova.loc['C(Target)', 'sum_sq'] / anova.loc['C(Target)', 'df']
    MS_e = anova.loc['Residual', 'sum_sq'] / anova.loc['Residual', 'df']
    k = len(df['Avaliador'].unique())
    return (MS_r - MS_e) / (MS_r + (k - 1) * MS_e)

icc_exp = calculate_icc(df_full[df_full['Turma'] == 'Grupo Experimental'])
icc_con = calculate_icc(df_full[df_full['Turma'] == 'Grupo Controle'])

df_icc = pd.DataFrame({
    'Comparação': ['Experimental (Caroline vs Guilherme)', 'Controle (Lierson vs Guilherme)'],
    'Métrica': ['ICC (Two-Way Mixed, Absolute Agreement)', 'ICC (Two-Way Mixed, Absolute Agreement)'],
    'Valor': [icc_exp, icc_con]
})

# --- 3.5. SALVAR TUDO EM EXCEL ---
relatorio_nome = 'Relatorio_Estatistico_IDSA.xlsx'
with pd.ExcelWriter(relatorio_nome, engine='openpyxl') as writer:
    df_global.to_excel(writer, sheet_name='Escore Global', index=False)
    df_shapiro.to_excel(writer, sheet_name='Normalidade (Shapiro)', index=False)
    df_criterios.to_excel(writer, sheet_name='Análise de Critérios (Holm)', index=False)
    df_icc.to_excel(writer, sheet_name='Concordância ICC', index=False)

print(f"-> Sucesso! Relatório salvo como '{relatorio_nome}'.")
print("O arquivo contém 4 abas: 'Escore Global', 'Normalidade (Shapiro)', 'Análise de Critérios (Holm)' e 'Concordância ICC'.")